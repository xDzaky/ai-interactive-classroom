/**
 * offlineOutbox.ts — P07-T04
 * Dexie IndexedDB database with an outbox table for offline-queued events
 * and a draft_boards table for persistent whiteboard state across reloads.
 *
 * Outbox record shape mirrors the POST /rooms/{room}/events payload so the
 * reconnect flush (P07-T05) can drain it straight to the API.
 */

import Dexie, { type Table } from "dexie";

// ---------------------------------------------------------------------------
// Outbox — pending events waiting to be synced to the server
// ---------------------------------------------------------------------------

export interface OutboxRecord {
  /** Auto-incremented local PK — used for iteration order */
  id?: number;
  /** UUID generated by the client — prevents duplicate commits after retry */
  idempotency_key: string;
  room_id: string;
  event_type: string;
  payload: Record<string, unknown>;
  /** false = pending, true = ACKed by server */
  committed: boolean;
  created_at: string; // ISO-8601
}

// ---------------------------------------------------------------------------
// Draft boards — latest local board state per room
// ---------------------------------------------------------------------------

export interface DraftBoardRecord {
  /** room_id is the primary key */
  room_id: string;
  /** Serialised BoardState (cast to unknown for storage) */
  state: Record<string, unknown>;
  /** seq at which this draft was saved */
  seq: number;
  saved_at: string; // ISO-8601
}

// ---------------------------------------------------------------------------
// Database
// ---------------------------------------------------------------------------

export class OutboxDatabase extends Dexie {
  outbox!: Table<OutboxRecord, number>;
  draft_boards!: Table<DraftBoardRecord, string>;

  constructor() {
    super("ai_classroom_outbox");
    this.version(1).stores({
      outbox:
        "++id, idempotency_key, room_id, committed, created_at",
      draft_boards: "room_id, seq, saved_at",
    });
  }
}

/** Singleton database instance */
export const db = new OutboxDatabase();

// ---------------------------------------------------------------------------
// Outbox helpers
// ---------------------------------------------------------------------------

/**
 * Add an event to the outbox.
 * Returns the auto-incremented id of the new record.
 */
export async function enqueue(
  record: Omit<OutboxRecord, "id" | "committed" | "created_at">,
): Promise<number> {
  return db.outbox.add({
    ...record,
    committed: false,
    created_at: new Date().toISOString(),
  });
}

/**
 * Return all un-committed outbox records for a room, ordered by id (insert order).
 */
export async function getPendingOutbox(roomId: string): Promise<OutboxRecord[]> {
  return db.outbox
    .where("room_id")
    .equals(roomId)
    .filter((r) => !r.committed)
    .sortBy("id");
}

/**
 * Mark an outbox record as committed (ACKed by server).
 */
export async function markCommitted(id: number): Promise<void> {
  await db.outbox.update(id, { committed: true });
}

/**
 * Delete all committed outbox records for a room (housekeeping).
 */
export async function pruneCommitted(roomId: string): Promise<void> {
  await db.outbox
    .where("room_id")
    .equals(roomId)
    .filter((r) => r.committed)
    .delete();
}

// ---------------------------------------------------------------------------
// Draft board helpers
// ---------------------------------------------------------------------------

/**
 * Save (upsert) the current draft board state for a room.
 */
export async function saveDraftBoard(
  roomId: string,
  state: Record<string, unknown>,
  seq: number,
): Promise<void> {
  await db.draft_boards.put({
    room_id: roomId,
    state,
    seq,
    saved_at: new Date().toISOString(),
  });
}

/**
 * Load the saved draft board state for a room, or null if none exists.
 */
export async function loadDraftBoard(
  roomId: string,
): Promise<DraftBoardRecord | null> {
  const record = await db.draft_boards.get(roomId);
  return record ?? null;
}

/**
 * Delete the draft board for a room (called when room session ends).
 */
export async function clearDraftBoard(roomId: string): Promise<void> {
  await db.draft_boards.delete(roomId);
}
